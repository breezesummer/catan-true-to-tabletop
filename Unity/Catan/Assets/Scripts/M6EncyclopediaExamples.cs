        string caption=e.first+" → "+e.next;
        TabletopTextFit.Fit(style,caption,label,19,true);
        GUI.Label(label,caption,style);
    }
    void DrawCardExample(string name){
        var e=BookExamples[name];
        DetailTab(new Rect(691,165,580,80),e.title,35);
        var tip=new Rect(682,287,350,180);
        var style=new GUIStyle(BookStyle(28)){alignment=TextAnchor.MiddleLeft};
        TabletopTextFit.Fit(style,e.tip,tip,22,true);GUI.Label(tip,e.tip,style);
        IllustratedExample(name,new Rect(1051,263,493,462),new Rect(682,488,348,182));
    }
    void DrawSkillExample(Catan.Core.ThreeKingdoms.GeneralDefinition general){
        var skills=general.Skills;
        bookSkillChoices.TryGetValue(general.Id,out int selected);
        float width=Mathf.Min(285f,880f/skills.Length);
        for(int i=0;i<skills.Length;i++){
            var tab=new Rect(640+i*width,246,width-9,68);
            if(i==selected)DetailTab(tab,skills[i].Name,32);
            else{DetailPage(tab);BookLabel(tab,skills[i].Name,28);}
            if(Hit(tab))bookSkillChoices[general.Id]=selected=i;
        }
        var skill=skills[selected];
        var area=new Rect(637,332,409,230);
        var style=new GUIStyle(BookStyle(26)){alignment=TextAnchor.MiddleLeft};
        TabletopTextFit.Fit(style,skill.OriginalText,area,20,true);
        var content=new GUIContent(skill.OriginalText);
        float height=style.CalcHeight(content,area.width-24);
        if(height<=area.height)GUI.Label(area,content,style);
        else{
            bookSkillScroll.TryGetValue(skill.Id,out var scroll);
            MobileTabletop.ScrollTouch(area,ref scroll);
            scroll=GUI.BeginScrollView(area,scroll,new Rect(0,0,area.width-24,height));
            GUI.Label(new Rect(0,0,area.width-24,height),content,style);
            GUI.EndScrollView();bookSkillScroll[skill.Id]=scroll;
        }
        IllustratedExample(skill.Id,new Rect(1064,322,475,405),new Rect(637,578,408,139));
    }
    readonly Dictionary<string,Vector2> bookSkillScroll=new Dictionary<string,Vector2>();
