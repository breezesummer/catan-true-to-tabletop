def illustration(kind):
    original=Image.open(ART/f'port-{kind}.png').convert('RGBA')
    mask=Image.new('L',(original.width*4,original.height*4))
    ImageDraw.Draw(mask).polygon([(x*4,y*4) for x,y in OUTLINE[kind]],fill=255)
    mask=mask.resize(original.size,Image.Resampling.LANCZOS)
    original.putalpha(mask)
    return original.crop(mask.getbbox())

def build():
    jade_base = runpy.run_path(str(ROOT/'art/recipes/jade-numbers/faces.py'))['jade_base']
    base = jade_base().resize(SIZE, Image.Resampling.BICUBIC).convert('RGBA')
    font = ImageFont.truetype('C:/Windows/Fonts/timesbd.ttf', 510)
    for kind in OUTLINE:
        panel = base.copy()
        art = illustration(kind)
        scale = min(760/art.width, 600/art.height)
        art = art.resize((round(art.width*scale), round(art.height*scale)), Image.Resampling.LANCZOS)
        pos = (512-art.width//2, 402-art.height//2)
        shadow = Image.new('RGBA', SIZE)
        ink = Image.new('RGBA', art.size, (65,43,25,255))
        ink.putalpha(art.getchannel('A').point(lambda value: round(value*.38)))
        shadow.alpha_composite(ink, (pos[0]+3,pos[1]+7))
        panel = Image.alpha_composite(panel, shadow.filter(ImageFilter.GaussianBlur(5)))
        panel.alpha_composite(art, pos)
        ratio = '3:1' if kind=='generic' else '2:1'
        mask = Image.new('L', (1100,650))
        ImageDraw.Draw(mask).text((0,0), ratio, font=font, fill=255)
        mask = mask.crop(mask.getbbox()).resize((790,400), Image.Resampling.LANCZOS)
        panel.paste((52,39,32,255), (117,735), mask)
        panel.convert('RGB').resize((1024,1024),Image.Resampling.LANCZOS).save(ART/f'sign-{kind}.png')

if __name__=='__main__':
    build()
