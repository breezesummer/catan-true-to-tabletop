from mathutils.bvhtree import BVHTree
from sculpt import P,V,C,S


NAMES = {"palm":"伸掌拦路","staff":"扶杖","embrace":"托袋","knifehand":"垂刀","visor":"遮眉","straphand":"扶带"}


def gesture(name, charts):
    if name == "embrace":
        # 指腹在变形完成的袋面上取深度；各指的第三值是到麻面的间隙。
        rows = next(ch.rows for ch in charts if ch.material == "sack" and ch.paint == "sack")
        n = len(rows[0])
        faces = [(j*n+k,j*n+(k+1)%n,(j+1)*n+(k+1)%n,(j+1)*n+k)
                 for j in range(len(rows)-1) for k in range(n)]
        tree = BVHTree.FromPolygons([p for r in rows for p in r], faces)
        def on_sack(x,y,clearance):
            hit = tree.ray_cast(P(x,y,-100),V((0,C,-S)),180)[0]
            if hit is None:
                raise ValueError("托袋手离开了麻袋的取样范围")
            return P(x,y,hit.y-clearance)
        wrist = on_sack(290,234.2,.8)
        fingers = [
            [(277.7,234.4,.1),(269.8,232.0,4.1),(258.6,229.8,4.0),(250.2,230.3,2.7)],
            [(265.8,241.9,4.6),(256.1,249.5,5.1),(249.4,253.1,4.3),(246.5,255.2,2.4)],
            [(270.1,247.7,5.2),(260.1,255.0,5.6),(253.4,260.0,4.1),(250.5,262.1,2.1)],
            [(274.6,253.1,4.6),(265.9,260.7,5.0),(259.8,265.0,3.6),(257.0,266.7,1.9)],
            [(279.0,257.8,3.5),(273.1,263.5,4.3),(268.2,267.5,3.5),(265.6,269.7,1.8)]]
        return wrist, [[on_sack(*p) for p in chain] for chain in fingers], (0,1,0),35.5
    wrist, fingers, palmar, scale = POSES[name]
    return P(*wrist), [[P(*p) for p in chain] for chain in fingers], palmar, scale


